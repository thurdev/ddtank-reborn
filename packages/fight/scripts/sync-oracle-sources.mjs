let cs = `// GENERATED by scripts/sync-oracle-sources.mjs from ${vendor.replace(/\\/g, "/")} — verbatim method bodies. Do not edit.\n`;
cs += usings.map((u) => `using ${u};`).join("\n") + "\n\n";
for (const [file, ns, header, sigs] of extracts) {
  const src = readFileSync(join(vendor, file), "utf8");
  const bodies = sigs.map((s) => `    // ${file}\n    ${extract(src, s, file)}`).join("\n\n");
  const cls = `${header}\n{\n${bodies}\n}\n`;
  cs += ns ? `namespace ${ns}\n{\n${cls}}\n\n` : cls + "\n";
  console.log(`${file}: extracted ${sigs.length} member(s)`);
}
writeFileSync(join(out, "Extracted.cs"), cs);
