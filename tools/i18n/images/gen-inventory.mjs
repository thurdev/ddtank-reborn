// Builds research/i18n/image-inventory.json + .md from the OCR sweep (ocr-full.ndjson).
import { readFileSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { buildTranslator } from "./lookup.mjs";

const SP = "C:/Users/T/AppData/Local/Temp/claude/C--Users-T-Documents-Projects-DDTank/c048f152-a1c9-45a2-b674-36b413e8f4d9/scratchpad";
const NDJSON = `${SP}/i18n/ocr-full.ndjson`;
const EXPORT_ROOT = `${SP}/i18n/ffdec_out`;
const ROOT = "C:/Users/T/Documents/Projects/DDTank";
const OUT_JSON = `${ROOT}/research/i18n/image-inventory.json`;
const OUT_MD = `${ROOT}/research/i18n/image-inventory.md`;

const PRIORITY_RULES = [
  { rank: 1, name: "loading", test: (s) => /^(loading\.swf|ddt_loading\.swf|[123]_loading\.swf)$/i.test(s) },
  { rank: 2, name: "hall/lobby", test: (s) => /^(hall\.swf|hall_old\.swf|serverlist\.swf|roomlist\.swf|toolbar\.swf)$/i.test(s) },
  {
    rank: 3,
    name: "main windows",
    test: (s) =>
      /^(store\.swf|ddtstore\.swf|bagandinfo.*\.swf|gameover\.swf|calendar\.swf|task\.swf|quest\.swf|wonderfulactivity\.swf|awardsystem.*\.swf|vipview\.swf|elitegame\.swf|worldboss\.swf|consortiabattle\.swf|cardsystem\.swf|labyrinth\.swf|league\.swf|luckstar.*\.swf|newchickenbox.*\.swf|newtitle\.swf|noviceactivity\.swf|roulette.*\.swf|firstrecharge\.swf|firsttainer\.swf|activeevents\.swf|consortia.*\.swf|consortion.*\.swf|forgemain.*\.swf|academy.*\.swf|auction\.swf|bank\.swf|farm\.swf)$/i.test(s),
  },
  {
    rank: 4,
    name: "buttons/titles/icons",
    test: (s) => /^(cursor\.swf|levelicon\.swf|ddthallicon\.swf|coreiconandtip.*\.swf|corei.*\.swf|core\.swf|coreii\.swf|gotopage\.swf)$/i.test(s),
  },
  {
    rank: 5,
    name: "combat",
    test: (s) => /^(room\.swf|hotspringroom.*\.swf|challengeroom\.swf|fightlib\.swf|churchroom.*\.swf|game\.swf|gameii\.swf)$/i.test(s),
  },
];
function classify(swf) {
  for (const r of PRIORITY_RULES) if (r.test(swf)) return { rank: r.rank, name: r.name };
  return { rank: 6, name: "rest" };
}

function parseCharId(file) {
  const m = file.match(/^(\d+)[_.]/);
  return m ? Number(m[1]) : null;
}

const translate = buildTranslator();

const lines = readFileSync(NDJSON, "utf8").split("\n").filter(Boolean);
const rows = [];
for (const line of lines) {
  const o = JSON.parse(line);
  if (!o.hasVN) continue;
  const text = o.text.replace(/\s+/g, " ").trim();
  if (text.length < 2) continue;
  const { rank, name } = classify(o.swf);
  const { pt, source } = translate(text);
  rows.push({
    swf: o.swf,
    file: o.file,
    path: `${o.swf}::${o.file}`,
    charId: parseCharId(o.file),
    w: o.w,
    h: o.h,
    size: o.size,
    ocrText: o.text,
    ocrConfidence: o.conf,
    screen: name,
    priority: rank,
    ptBrSuggestion: pt,
    ptBrSource: source,
  });
}
rows.sort((a, b) => a.priority - b.priority || b.size - a.size);

writeFileSync(OUT_JSON, JSON.stringify({ generatedAt: new Date().toISOString(), totalImagesScanned: lines.length, totalWithVnText: rows.length, rows }, null, 1));

const bySwf = new Map();
for (const r of rows) {
  if (!bySwf.has(r.swf)) bySwf.set(r.swf, []);
  bySwf.get(r.swf).push(r);
}
const byPriority = new Map();
for (const r of rows) {
  if (!byPriority.has(r.priority)) byPriority.set(r.priority, 0);
  byPriority.set(r.priority, byPriority.get(r.priority) + 1);
}

let md = `# Image inventory — Vietnamese-text images across all client SWFs (full sweep)\n\n`;
md += `Generated by \`tools/i18n/images/gen-inventory.mjs\` from an FFDec image export of all ${119} client SWFs `;
md += `(every \`ui/vietnam/swf/*.swf\` + \`Loading.swf\`/\`DDT_Loading.swf\`/\`1.png\`,\`2.png\`,\`3.png\` — the last three are `;
md += `SWF data disguised with a .png extension) and a tesseract.js (\`vie\` language) OCR pass over every exported `;
md += `bitmap. See \`research/i18n/image-inventory.json\` for the full machine-readable row set (this file is a `;
md += `human-readable summary — only a sample of rows per SWF is listed below to keep the file reviewable).\n\n`;
md += `**Totals**: ${lines.length} images scanned, **${rows.length}** flagged with Vietnamese diacritics (false positives from noisy OCR on decorative/item art are expected and were not manually cleared — see "Method" below).\n\n`;
md += `**By priority**: ${[...byPriority.entries()].sort((a, b) => a[0] - b[0]).map(([p, n]) => `P${p} (${PRIORITY_RULES.find((r) => r.rank === p)?.name ?? "rest"})=${n}`).join(", ")}\n\n`;
md += `## Method\n\n`;
md += `1. \`export-all.sh\` runs \`ffdec-cli -export image\` per SWF (resumable, skips already-exported dirs).\n`;
md += `2. \`ocr-scan.mjs\` runs every exported PNG/JPG through tesseract.js \`vie\`, normalizing size (upscale <200px, downscale >900px) for speed/accuracy, writing one NDJSON row per image with the recognized text.\n`;
md += `3. A row is kept here only if the OCR text contains a Vietnamese-specific diacritic character (ăâđêôơư + tone marks) — garbled OCR on photographic/painterly art (character portraits, map thumbnails) can still trip this heuristic; those are the main source of false positives in a full un-reviewed sweep like this one. Treat \`ocrText\` as a strong hint, not ground truth — open the image before using it.\n`;
md += `4. \`ptBrSuggestion\`/\`ptBrSource\` come from (in order) the hand-curated top-priority caption map, an exact-phrase match against \`language.txt\` (VI) <-> \`data/i18n/pt-BR/client-language.txt\` (same key order), the MT cache from the DB/text localization batch, or a glossary.json substring substitution. \`null\` means nothing matched yet — translate in a batch before rendering.\n\n`;
md += `## Priority definitions\n\n`;
md += `| Priority | Screens | SWFs |\n|---|---|---|\n`;
for (const r of PRIORITY_RULES) md += `| P${r.rank} | ${r.name} | — |\n`;
md += `| P6 | rest (everything else: chat, email, farm, trainer*, guild/consortia internals, church, totem, forge detail windows, misc activity SWFs) | — |\n\n`;

md += `## Per-SWF summary (sample rows, highest-value first within each file)\n\n`;
const swfOrder = [...bySwf.keys()].sort((a, b) => {
  const ra = classify(a).rank,
    rb = classify(b).rank;
  return ra - rb || bySwf.get(b).length - bySwf.get(a).length;
});
for (const swf of swfOrder) {
  const list = bySwf.get(swf);
  const { name } = classify(swf);
  md += `### ${swf} (${name}, P${classify(swf).rank}) — ${list.length} flagged image(s)\n\n`;
  md += `| File | Size | WxH | OCR text | PT-BR suggestion |\n|---|---|---|---|---|\n`;
  for (const r of list.slice(0, 15)) {
    const short = r.ocrText.replace(/\n/g, " / ").slice(0, 90);
    md += `| \`${r.file}\` | ${r.size}B | ${r.w}x${r.h} | ${short.replace(/\|/g, "\\|")} | ${r.ptBrSuggestion ? r.ptBrSuggestion.replace(/\|/g, "\\|") : "_(needs translation)_"} |\n`;
  }
  if (list.length > 15) md += `| _(+${list.length - 15} more — see JSON)_ | | | | |\n`;
  md += `\n`;
}

writeFileSync(OUT_MD, md);
console.log(`wrote ${OUT_JSON} (${rows.length} rows) and ${OUT_MD}`);
