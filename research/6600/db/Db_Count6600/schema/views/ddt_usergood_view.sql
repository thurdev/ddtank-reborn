CREATE VIEW [dbo].[ddt_usergood_view]
AS
SELECT     0 AS UserId, CAST('' AS Varchar(50)) AS UserName, CAST('' AS Varchar(50)) AS NickName, CAST('' AS Varchar(20)) AS Sex, CAST('' AS Varchar(20)) 
                      AS Gold, CAST('' AS Varchar(20)) AS Money, CAST('' AS Varchar(20)) AS LastDate, CAST('' AS Varchar(20)) AS Type


GO
