CREATE VIEW [dbo].[Count_GoodPay_view]
AS
SELECT CAST(0 AS Int) AS goodId, CAST('' AS Varchar(200)) AS name, CAST(0 AS Int) AS countMoney, CAST(0 AS Int) AS countGiftToken, CAST(0 AS Int) AS countOffer, CAST(0 AS Int) AS countOtherPay, CAST(0 AS Int) AS countGold


GO
